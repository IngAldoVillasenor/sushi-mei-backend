SELECT u.id, b.id, u.role, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0
FROM app_users u
CROSS JOIN businesses b
WHERE b.name = 'Sushi Mei'
  AND NOT EXISTS (
      SELECT 1 FROM business_memberships m
      WHERE m.user_id = u.id AND m.business_id = b.id
