CREATE TABLE public.cart (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.cart_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ) NOT NULL,
    phone_number character varying(255),
    status character varying(255),
    CONSTRAINT cart_pkey PRIMARY KEY (id)
);

